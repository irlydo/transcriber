_current = "en"


def system_language() -> str:
    """The Windows display language, if the app has a translation for it, else English."""
    name = ""
    try:
        langid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        # Match on the primary language so regional variants (e.g. es-MX) still resolve.
        name = locale.windows_locale.get(langid) or next(
            (v for k, v in locale.windows_locale.items() if k & 0x3FF == langid & 0x3FF), "")
    except (AttributeError, OSError):
        name = locale.getlocale()[0] or ""
    code = name.split("_")[0].lower()
    return code if code in STRINGS else "en"


def set_language(code: str) -> None:
    """Pick the interface language; "system" (or anything unknown) follows Windows."""
    global _current
    _current = code if code in STRINGS else system_language()


def current_language() -> str:
    return _current


def t(key: str, **kwargs) -> str:
    text = STRINGS[_current].get(key) or STRINGS["en"][key]
    return text.format(**kwargs) if kwargs else text
